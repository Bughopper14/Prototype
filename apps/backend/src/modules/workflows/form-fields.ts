/** The definition of a field by its form, section and code. */
export const formField = (form: string, section: string, code: string) => bySectionCode.get(`${form}|${section}|${code}`);

/** Every definition that has this code (the same code can exist in several sections). */
export const fieldsByCode = (code: string) => byCode.get(code) || [];
